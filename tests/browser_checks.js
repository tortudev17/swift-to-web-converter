// Run after opening the generated SwiftDemo HTML with playwright-cli.
// playwright-cli run-code --filename tests/browser_checks.js
async page => {
  const assert = (condition, message) => {if (!condition) throw new Error(message);};
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.reload();
  assert(await page.evaluate(() => getComputedStyle(document.documentElement).fontFamily.startsWith('Helvetica Neue')), 'Helvetica Neue font stack');
  assert(await page.getByText('Local points: 4', {exact: true}).count() === 1, 'Literal model and pure Swift loop method calculate points');
  await page.getByRole('button', {name: 'Reset', exact: true}).click();
  assert(await page.getByText('Count: 0', {exact: true}).count() === 1, 'Reset counter');
  await page.getByRole('button', {name: 'Increment', exact: true}).click();
  assert(await page.getByText('Count: 1', {exact: true}).count() === 1, 'Increment counter');
  assert(await page.getByRole('img', {name: 'gear'}).evaluate(img => img.complete && img.naturalWidth > 0 && img.src.startsWith('data:image/svg+xml;base64,')), 'Named ForEach prefix conditional embeds gear image');
  assert(await page.getByText('Count: 1', {exact: true}).evaluate(el => el.classList.contains('swiftui-value-change') && getComputedStyle(el).animationName.includes('swiftui-value-change')), 'State text animates');
  await page.getByRole('textbox', {name: 'Your name'}).fill('Adrian');
  assert(await page.getByText('Hello, Adrian!', {exact: true}).count() === 1, 'Text binding');
  await page.getByRole('textbox', {name: 'Your name'}).press('End');
  await page.getByRole('textbox', {name: 'Your name'}).press('!');
  assert(await page.getByText('Hello, Adrian!!', {exact: true}).count() === 1, 'Typing and focus restoration');
  await page.getByRole('checkbox', {name: 'Show count'}).uncheck();
  assert(await page.getByRole('checkbox', {name: 'Show count'}).evaluate(el => el.classList.contains('swiftui-toggle-change') && getComputedStyle(el, '::after').animationName.includes('swiftui-toggle-knob-off')), 'Toggle animates off');
  assert(await page.getByText('Count hidden', {exact: true}).count() === 1, 'Conditional false branch');
  assert(await page.getByText('Count hidden', {exact: true}).evaluate(el => el.classList.contains('swiftui-content-enter')), 'Conditional content animates');
  await page.getByRole('checkbox', {name: 'Show count'}).check();
  assert(await page.getByRole('checkbox', {name: 'Show count'}).evaluate(el => getComputedStyle(el, '::after').animationName.includes('swiftui-toggle-knob-on')), 'Toggle animates on');
  assert(await page.getByText('Count: 1', {exact: true}).count() === 1, 'Conditional preserves state');
  await page.getByRole('button', {name: 'Select Apple', exact: true}).click();
  assert(await page.getByText('Selected', {exact: true}).count() === 1, 'Per-row state');
  await page.getByRole('button', {name: 'Select Pear', exact: true}).click();
  assert(await page.getByText('Selected', {exact: true}).count() === 2, 'Independent row state');
  await page.getByRole('button', {name: 'Select Apple', exact: true}).click();
  assert(await page.getByText('Selected', {exact: true}).count() === 1, 'Toggle row state');
  assert(await page.getByRole('img', {name: 'Badge'}).evaluate(img => img.complete && img.naturalWidth > 0 && img.src.startsWith('data:')), 'Embedded image loads');
  await page.getByRole('button', {name: 'Details', exact: true}).click();
  assert(await page.getByText('Details screen', {exact: true}).count() === 1, 'Navigation destination');
  assert(await page.getByText('40 pt sample', {exact: true}).evaluate(el => getComputedStyle(el).fontSize === '40px'), 'System font size modifier');
  assert(await page.getByText('Padding sample', {exact: true}).evaluate(el => getComputedStyle(el.parentElement).paddingInline === '12px' && getComputedStyle(el.parentElement.parentElement).paddingTop === '5px'), 'Custom per-edge padding');
  assert(await page.locator('.swiftui-navigation-push').evaluate(el => getComputedStyle(el).animationName.includes('swiftui-navigation-push')), 'Navigation push animates');
  assert(await page.getByRole('button', {name: 'Increment', exact: true}).count() === 0, 'Root hidden during navigation');
  await page.getByRole('button', {name: '‹ Swift Demo', exact: true}).click();
  assert(await page.getByText('Count: 1', {exact: true}).count() === 1, 'Back preserves root state');
  assert(await page.locator('.swiftui-navigation-pop').evaluate(el => getComputedStyle(el).animationName.includes('swiftui-navigation-pop')), 'Navigation back animates');
  assert(await page.getByRole('textbox', {name: 'Your name'}).inputValue() === 'Adrian!', 'Back preserves input');
  await page.getByText('Conversion report (0 warnings)', {exact: true}).click();
  assert(await page.getByText('No unsupported features detected in the parsed subset.', {exact: true}).isVisible(), 'Embedded report');
  await page.setViewportSize({width: 390, height: 844});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile horizontal overflow');
  await page.screenshot({path: 'output/playwright/mobile.png', fullPage: true});
  await page.setViewportSize({width: 1280, height: 900});
  await page.screenshot({path: 'output/playwright/desktop.png', fullPage: true});
  await page.reload();
  await page.setViewportSize({width: 368, height: 800});
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({path: 'output/playwright/web-ios-sized.png'});
  const requests = [];
  page.on('request', request => requests.push(request.url()));
  await page.context().setOffline(true);
  await page.reload();
  assert(await page.getByText('Hello, World!', {exact: true}).count() === 1, 'Offline file reload');
  assert(await page.getByRole('img', {name: 'Badge'}).evaluate(img => img.complete && img.naturalWidth > 0), 'Offline image');
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.getByRole('button', {name: 'Increment', exact: true}).click();
  assert(await page.getByText('Count: 1', {exact: true}).evaluate(el => parseFloat(getComputedStyle(el).animationDuration) <= 0.00001), 'Reduced motion preference is honored');
  assert(requests.every(url => url.startsWith('file:') || url.startsWith('data:')), 'No external dependencies');
  assert(errors.length === 0, `Browser errors: ${errors.join(', ')}`);
  return 'PASS: Helvetica Neue, parenthesized Button closures, named ForEach prefix and gear image, counter and value animation, input/focus, animated toggle, conditional entry, independent row state, 40px system font, custom edge padding, animated navigation/back, embedded asset image/report, mobile layout, offline reload, reduced-motion preference, and no external requests.';
}
